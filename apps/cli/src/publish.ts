import type { Asset, Compilation } from '@roadmark/compiler/model';

import { compileWorkspace } from '@roadmark/compiler/compile';
import { renderSite } from '@roadmark/web/render';
import { Effect, FileSystem, Schema } from 'effect';
import { createHash } from 'node:crypto';
import { constants, createReadStream } from 'node:fs';
import {
  copyFile,
  lstat,
  mkdir,
  readFile,
  readdir,
  realpath,
  rename,
  rm,
  writeFile,
} from 'node:fs/promises';
import path from 'node:path';
import lockfile from 'proper-lockfile';
import sharp from 'sharp';

import { hasFailures } from './diagnostics.ts';
import { errorText, hasCode, runPromise } from './run.ts';
import { verifyPages } from './verify-pages.ts';

/**
 * Filename identifying a directory previously generated by the roadmap publisher.
 */
const marker = '.roadmark-site.json';

/**
 * Workspace paths that an output directory must never replace.
 */
const sourceNames = [
  'feature-sets',
  'releases',
  'roadmap.yaml',
  'people.yaml',
  'teams.yaml',
  'brand.yaml',
  'brand',
];

/**
 * Generator identity stored in and verified against the output marker.
 */
const managedBy = 'roadmark';

/**
 * Generated files written at once while staging a site. Each write targets a distinct path.
 */
const WRITE_CONCURRENCY = 16;

/**
 * Verifies the generator identity without requiring a particular marker version.
 */
const decodeOwnershipMarker = Schema.decodeUnknownEffect(
  Schema.fromJsonString(
    Schema.Struct({
      /**
       * Identifies the publisher that owns the generated directory.
       */
      generator: Schema.Literal(managedBy),
    }),
  ),
);

/**
 * Serializes the ownership marker written into every published site.
 */
const encodeSiteMarker = Schema.encodeEffect(
  Schema.fromJsonString(
    Schema.Struct({
      /**
       * Identifies the publisher that owns the generated directory.
       */
      generator: Schema.Literal(managedBy),

      /**
       * Marker format version.
       */
      version: Schema.Literal(1),

      /**
       * Deployment prefix read back by preview.
       */
      base: Schema.String,
    }),
  ),
);

/**
 * A site that could not be published, with the reason shown to the author.
 */
export class PublishError extends Schema.TaggedError<
  PublishError,
  {
    /**
     * Distinguishes publish errors from structurally similar values.
     */
    readonly brand: unique symbol;
  }
>()('PublishError', {
  /**
   * Explains why the output was left unchanged.
   */
  message: Schema.String,
}) {}

/**
 * Canonical paths of one publish transaction.
 */
type Stage = {
  /**
   * Canonical workspace root.
   */
  root: string;

  /**
   * Canonical output directory that receives the finished site.
   */
  target: string;

  /**
   * Sibling directory holding the staged site and the replaced one during the swap.
   */
  transaction: string;

  /**
   * Slash-terminated deployment prefix.
   */
  base: string;

  /**
   * The compiled workspace to render.
   */
  model: Compilation;
};

/**
 * Compiles and promotes a fully verified site. Invalid content leaves earlier builds usable.
 *
 * @param root The workspace directory.
 * @param out The output directory.
 * @param base The slash-terminated deployment prefix.
 * @param strict Whether warnings prevent publishing.
 * @returns The compilation, published unless it has failures.
 */
export const publishSite = Effect.fn('publishSite')(function* (
  root: string,
  out: string,
  base: string,
  strict: boolean,
): Effect.fn.Return<Compilation, PublishError, FileSystem.FileSystem> {
  const source = yield* attempt(() => realpath(root));
  const target = yield* destination(source, out);
  yield* attempt(() => mkdir(path.dirname(target), { recursive: true }));
  return yield* Effect.scoped(
    Effect.gen(function* () {
      yield* outputLock(target);
      const transaction = target + '.roadmap-transaction';
      yield* restoreInterrupted(target, transaction);
      yield* checkOwnership(target);
      const model = yield* compileWorkspace(source, base).pipe(
        Effect.mapError((error) => new PublishError({ message: error.message })),
      );
      if (hasFailures(model.diagnostics, strict)) {
        return model;
      }

      if (model.assets.some((asset) => inside(target, path.join(source, asset.source)))) {
        return yield* failWith(`Output overlaps roadmap assets: ${target}`);
      }

      yield* stageSite({ root: source, target, transaction, base, model });
      return model;
    }),
  );
});

/**
 * Promise facade over {@link publishSite} for callers outside Effect.
 *
 * @param root The workspace directory.
 * @param out The output directory.
 * @param base The slash-terminated deployment prefix.
 * @param strict Whether warnings prevent publishing.
 * @returns The compilation, published unless it has failures.
 */
export function publish(
  root: string,
  out: string,
  base: string,
  strict = false,
): Promise<Compilation> {
  return runPromise(publishSite(root, out, base, strict));
}

/**
 * Holds the output lock for the rest of the scope.
 */
function outputLock(target: string) {
  return Effect.acquireRelease(
    attempt(() =>
      lockfile.lock(target, { realpath: false, lockfilePath: target + '.roadmap-lock' }),
    ),
    (release) => Effect.promise(() => release()),
  );
}

/**
 * Opens the transaction, builds the replacement tree and swaps it into place. The transaction is
 * always resolved afterwards, restoring the previous site if the swap was interrupted.
 */
function stageSite(stage: Stage): Effect.Effect<void, PublishError, FileSystem.FileSystem> {
  return Effect.acquireUseRelease(
    openTransaction(stage.target, stage.transaction),
    () => writeAndSwap(stage),
    () => restoreInterrupted(stage.target, stage.transaction),
  );
}

/**
 * Claims the transaction path with an owner file, created in a scoped staging directory beside the
 * output so the rename stays on one filesystem.
 */
function openTransaction(target: string, transaction: string) {
  return Effect.scoped(
    Effect.gen(function* () {
      const fs = yield* FileSystem.FileSystem;
      const temporary = yield* fs
        .makeTempDirectoryScoped({ directory: path.dirname(target), prefix: '.roadmap-stage-' })
        .pipe(Effect.mapError((error) => new PublishError({ message: error.message })));
      yield* attempt(() => writeFile(path.join(temporary, 'owner'), target, { flag: 'wx' }));
      yield* attempt(() => rename(temporary, transaction));
    }),
  );
}

/**
 * Renders, verifies and writes the staged site, then swaps it with the current output.
 */
const writeAndSwap = Effect.fnUntraced(function* (stage: Stage) {
  const { root, target, transaction, base, model } = stage;
  const staging = path.join(transaction, 'next');
  yield* attempt(() => mkdir(staging));
  const files = yield* attempt(() => renderSite(model, base));
  yield* attempt(async () => {
    const names = new Set(files.keys());
    for (const asset of model.assets) {
      claim(names, asset.output);
      if (asset.poster) {
        claim(names, asset.poster);
      }
    }

    verifyPages(files, names, base);
  });
  yield* Effect.forEach(files, ([name, bytes]) => writeStaged(staging, name, bytes), {
    concurrency: WRITE_CONCURRENCY,
    discard: true,
  });
  yield* Effect.forEach(model.assets, (asset) => attempt(() => copyAsset(root, staging, asset)), {
    discard: true,
  });
  const ownership = yield* encodeSiteMarker({ generator: managedBy, version: 1, base }).pipe(
    Effect.mapError((error) => new PublishError({ message: error.message })),
  );
  yield* attempt(() => writeFile(path.join(staging, marker), ownership + '\n', { flag: 'wx' }));
  yield* swap(target, staging, path.join(transaction, 'previous'));
});

/**
 * Moves the current site aside and the staged one into place as one step that interruption cannot
 * split, so recovery never inspects the transaction while a rename is still in flight.
 */
function swap(
  target: string,
  staging: string,
  previous: string,
): Effect.Effect<void, PublishError> {
  return Effect.gen(function* () {
    if (yield* exists(target)) {
      yield* checkOwnership(target);
      yield* attempt(() => rename(target, previous));
    }

    yield* attempt(() => rename(staging, target));
  }).pipe(Effect.uninterruptible);
}

/**
 * Writes one generated file beneath the staging directory without overwriting.
 */
function writeStaged(
  staging: string,
  name: string,
  bytes: string | Uint8Array,
): Effect.Effect<void, PublishError> {
  return attempt(async () => {
    const file = localPath(staging, name);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, bytes, { flag: 'wx' });
  });
}

/**
 * Reserves an output path and rejects competing generators.
 */
function claim(names: Set<string>, name: string): void {
  if (names.has(name)) {
    throw new Error(`Duplicate generated path: ${name}`);
  }

  names.add(name);
}

/**
 * Copies and verifies a content-addressed file and generates its poster if requested.
 */
async function copyAsset(root: string, staging: string, asset: Asset): Promise<void> {
  const source = await realpath(localPath(root, asset.source));
  if (!inside(root, source)) {
    throw new Error(`Media escapes the workspace: ${asset.source}`);
  }

  const output = localPath(staging, asset.output);
  await mkdir(path.dirname(output), { recursive: true });
  if (asset.bytes) {
    await writeFile(output, asset.bytes, { flag: 'wx' });
  } else {
    // FileSystem.copyFile has no exclusive mode; COPYFILE_EXCL refuses to replace a staged file.
    await copyFile(source, output, constants.COPYFILE_EXCL);
  }

  const hash = createHash('sha256');
  // A file stream without an encoding emits buffers.
  const bytes = createReadStream(output) as AsyncIterable<Buffer>;
  for await (const chunk of bytes) {
    hash.update(chunk);
  }

  if (!hash.digest('hex').startsWith(path.parse(output).name)) {
    throw new Error(`Media changed while building: ${asset.source}. Run the build again.`);
  }

  if (asset.poster) {
    const poster = localPath(staging, asset.poster);
    await mkdir(path.dirname(poster), { recursive: true });
    await sharp(output, { page: 0, pages: 1 }).png().toFile(poster);
  }
}

/**
 * Canonicalizes the build directory and protects the authoring workspace.
 */
const destination = Effect.fnUntraced(function* (root: string, out: string) {
  let ancestor = path.resolve(out);
  const missing: Array<string> = [];
  while (!(yield* exists(ancestor))) {
    missing.unshift(path.basename(ancestor));
    ancestor = path.dirname(ancestor);
  }

  const parent = ancestor;
  if ((yield* attempt(() => lstat(parent))).isSymbolicLink()) {
    return yield* failWith(`Choose an output directory outside symbolic links: ${parent}`);
  }

  const target = path.join(yield* attempt(() => realpath(parent)), ...missing);
  if (inside(target, root) || sourceNames.some((name) => inside(path.join(root, name), target))) {
    return yield* failWith(`Output overlaps roadmap sources: ${target}`);
  }

  return target;
});

/**
 * Allows replacement of empty directories and sites created by this publisher.
 */
function checkOwnership(target: string): Effect.Effect<void, PublishError> {
  return exists(target).pipe(
    Effect.flatMap((present) => (present ? checkReplaceable(target) : Effect.void)),
  );
}

/**
 * Rejects an existing output that is not a directory or holds files from another source.
 */
function checkReplaceable(target: string): Effect.Effect<void, PublishError> {
  return attempt(() => lstat(target)).pipe(
    Effect.filterOrFail(
      (info) => info.isDirectory() && !info.isSymbolicLink(),
      () => new PublishError({ message: `Output must be a directory: ${target}` }),
    ),
    Effect.andThen(attempt(() => readdir(target))),
    Effect.flatMap((entries) =>
      entries.length === 0 ? Effect.succeed(true) : ownedByPublisher(path.join(target, marker)),
    ),
    Effect.filterOrFail(
      (owned) => owned,
      () =>
        new PublishError({
          message: `Output contains files from another source: ${target}. Choose an empty directory.`,
        }),
    ),
    Effect.asVoid,
  );
}

/**
 * Accepts an output marker only if it is a regular file naming this generator.
 */
function ownedByPublisher(markerFile: string): Effect.Effect<boolean> {
  return attempt(() => lstat(markerFile)).pipe(
    Effect.flatMap((info) =>
      info.isFile()
        ? attempt(() => readFile(markerFile, 'utf8')).pipe(
            Effect.flatMap(decodeOwnershipMarker),
            Effect.as(true),
          )
        : Effect.succeed(false),
    ),
    Effect.orElseSucceed(() => false),
  );
}

/**
 * Recovers a previous site after termination between the two directory renames.
 */
function restoreInterrupted(
  target: string,
  transaction: string,
): Effect.Effect<void, PublishError> {
  return exists(transaction).pipe(
    Effect.flatMap((present) => (present ? closeTransaction(target, transaction) : Effect.void)),
  );
}

/**
 * Moves a stranded previous site back into place and removes the transaction directory.
 */
function closeTransaction(target: string, transaction: string): Effect.Effect<void, PublishError> {
  const owner = path.join(transaction, 'owner');
  const previous = path.join(transaction, 'previous');
  const valid = attempt(
    async () =>
      (await lstat(transaction)).isDirectory() &&
      (await lstat(owner).catch(() => undefined))?.isFile() === true &&
      (await readFile(owner, 'utf8')) === target,
  );
  const restore = Effect.all([exists(previous), exists(target)]).pipe(
    Effect.flatMap(([stranded, present]) =>
      stranded && !present ? attempt(() => rename(previous, target)) : Effect.void,
    ),
  );
  return valid.pipe(
    Effect.filterOrFail(
      (owned) => owned,
      () =>
        new PublishError({
          message: `Build transaction path is occupied: ${transaction}. Choose another output directory.`,
        }),
    ),
    Effect.andThen(restore),
    Effect.andThen(attempt(() => rm(transaction, { recursive: true }))),
  );
}

/**
 * Resolves a relative path and rejects a result outside the permitted root.
 */
function localPath(root: string, name: string): string {
  const output = path.resolve(root, name);
  if (path.isAbsolute(name) || output === root || !inside(root, output)) {
    throw new Error(`Path escapes output directory: ${name}`);
  }

  return output;
}

/**
 * Tests lexical containment using the platform path separator.
 */
function inside(parent: string, child: string): boolean {
  const relative = path.relative(parent, child);
  return relative !== '..' && !relative.startsWith('..' + path.sep) && !path.isAbsolute(relative);
}

/**
 * Checks for a filesystem entry while propagating errors other than absence.
 */
function exists(file: string): Effect.Effect<boolean, PublishError> {
  return attempt(() =>
    lstat(file).then(
      () => true,
      (error: unknown) => {
        if (hasCode(error, 'ENOENT')) {
          return false;
        }

        throw error;
      },
    ),
  );
}

/**
 * Fails the publish with an author-facing message.
 */
function failWith(message: string): Effect.Effect<never, PublishError> {
  return Effect.fail(new PublishError({ message }));
}

/**
 * Runs one filesystem or rendering step, keeping the underlying error's message. The step is not
 * interruptible: an interrupted promise keeps running, and the transaction's cleanup must not race
 * a write or rename that is still in flight.
 */
function attempt<A>(run: () => Promise<A>): Effect.Effect<A, PublishError> {
  return Effect.tryPromise({
    try: run,
    catch: (cause) => new PublishError({ message: errorText(cause) }),
  }).pipe(Effect.uninterruptible);
}
